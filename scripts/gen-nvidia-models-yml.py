#!/usr/bin/env python3
"""Generate ~/.omp/agent/models.yml from the NVIDIA InferenceHub metadata API.

Mirrors sixuerain/pi's nvidia-inference-hub provider (packages/ai/src/providers/
nvidia-inference-hub.ts): every chat-capable model in the hub catalog becomes an
omp custom model routed to its own LiteLLM proxy URL.

Requires NVIDIA_INFERENCEHUB_METADATA_KEY (catalog) and optionally
NVIDIA_INFERENCEHUB_API_KEY / OPENAI_BASE_URL (exported in ~/.bashrc).

Re-run any time the hub catalog changes:  python3 gen-nvidia-models-yml.py
"""

import json
import os
import sys
import urllib.request

METADATA_BASE = "https://inference-backend.nvidia.com/api/v1"
OUT_PATH = os.path.expanduser("~/.omp/agent/models.yml")
PROVIDER_ID = "nvidia-inference-hub"

# Static internal providers (from ~/.pi/agent/models.json of the pi fork)
LOCAL_PROVIDERS = {
    "0-local-galaxy1": {
        "baseUrl": "http://10.32.186.146:15123/v1",
        "models": [
            {
                "id": "glm-5.3-flash",
                "name": "GLM 5.3 Flash (local vLLM)",
                "contextWindow": 1048576,
                "maxTokens": 32768,
                "compat": {
                    "supportsDeveloperRole": False,
                    "supportsReasoningEffort": True,
                    "maxTokensField": "max_tokens",
                },
            }
        ],
    },
    "0-local-galaxy2": {
        "baseUrl": "http://10.32.186.215:15123/v1",
        "models": [
            {
                "id": "deepseek-v4-flash",
                "name": "DeepSeek V4 Flash (local vLLM)",
                "contextWindow": 1048576,
                "maxTokens": 32768,
                "compat": {
                    "supportsDeveloperRole": False,
                    "maxTokensField": "max_tokens",
                },
            }
        ],
    },
}


def classify_endpoint(url):
    if url.endswith("/chat/completions"):
        return url[: -len("/chat/completions")], "openai-completions"
    if url.endswith("/responses"):
        return url[: -len("/responses")], "openai-responses"
    return None, None


def fetch_models(metadata_key):
    models, page = [], 1
    while True:
        url = f"{METADATA_BASE}/models/slim?category=Text%20Generation&page={page}&page_size=100"
        req = urllib.request.Request(url, headers={"X-API-Key": metadata_key})
        with urllib.request.urlopen(req, timeout=30) as resp:
            data = json.load(resp)
        models.extend(data.get("models", []))
        if page >= data.get("total_pages", 1):
            break
        page += 1
    return models


def yaml_str(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    metadata_key = os.environ.get("NVIDIA_INFERENCEHUB_METADATA_KEY")
    api_key_env = "NVIDIA_INFERENCEHUB_API_KEY"
    fallback_base = os.environ.get("OPENAI_BASE_URL")
    if not metadata_key:
        sys.exit("NVIDIA_INFERENCEHUB_METADATA_KEY not set")
    if not fallback_base:
        sys.exit("OPENAI_BASE_URL not set (needed as provider-level baseUrl)")

    slim_models = fetch_models(metadata_key)
    entries = []
    for m in slim_models:
        if not m.get("supports_chat") or not m.get("litellm_proxy_url"):
            continue
        base, api = classify_endpoint(m["litellm_proxy_url"])
        if not base:
            continue
        input_types = '["text", "image"]' if m.get("supports_vlm") else '["text"]'
        ctx = m.get("context_length_tokens") or 128000
        entries.append(
            {
                "id": m["label"],
                "name": m["name"],
                "baseUrl": base,
                "api": api,
                "input": input_types,
                "contextWindow": ctx,
            }
        )
    entries.sort(key=lambda e: e["id"])

    lines = [
        "# NVIDIA InferenceHub catalog for omp — generated by scripts/gen-nvidia-models-yml.py.",
        "# Re-run that script to refresh; manual edits will be overwritten.",
        "providers:",
        f"  {PROVIDER_ID}:",
        "    apiKey: NVIDIA_INFERENCEHUB_API_KEY",
        "    api: openai-completions",
        f"    baseUrl: {fallback_base}",
        "    models:",
    ]
    for e in entries:
        lines.append(f"      - id: {yaml_str(e['id'])}")
        lines.append(f"        name: {yaml_str(e['name'])}")
        lines.append(f"        baseUrl: {e['baseUrl']}")
        lines.append(f"        api: {e['api']}")
        lines.append(f"        input: {e['input']}")
        lines.append("        reasoning: false")
        lines.append("        cost:")
        lines.append("          input: 0")
        lines.append("          output: 0")
        lines.append("          cacheRead: 0")
        lines.append("          cacheWrite: 0")
        lines.append(f"        contextWindow: {e['contextWindow']}")
        lines.append("        maxTokens: 4096")

    # Static internal providers (same definition as the pi fork's models.json)
    for pid, p in LOCAL_PROVIDERS.items():
        lines.append(f"  {pid}:")
        lines.append(f"    baseUrl: {p['baseUrl']}")
        lines.append("    apiKey: EMPTY")
        lines.append("    api: openai-completions")
        lines.append("    models:")
        for m in p["models"]:
            lines.append(f"      - id: {m['id']}")
            lines.append(f"        name: {m['name']}")
            lines.append(f"        contextWindow: {m['contextWindow']}")
            lines.append(f"        maxTokens: {m['maxTokens']}")
            lines.append("        reasoning: true")
            lines.append("        input: [text]")
            lines.append("        cost:")
            lines.append("          input: 0")
            lines.append("          output: 0")
            lines.append("          cacheRead: 0")
            lines.append("          cacheWrite: 0")
            lines.append("        compat:")
            for ck, cv in m["compat"].items():
                lines.append(f"          {ck}: {str(cv).lower()}")

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT_PATH}: {len(entries)} models from {len(slim_models)} catalog rows")


if __name__ == "__main__":
    main()
